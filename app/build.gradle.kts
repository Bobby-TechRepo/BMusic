android {
    namespace = "com.bsoft.compose.bmusic"
    compileSdk {
        version = release(37) {
            minorApiLevel = 0
        }
    }

    defaultConfig {
        applicationId = "com.bsoft.compose.bmusic"
        minSdk = 26
        targetSdk = 37
        versionCode = providers.gradleProperty("versionCode")
            .orElse("1")
            .get()
            .toInt()

        versionName = providers.gradleProperty("versionName")
            .orElse("1.0.0")
            .get()

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        androidResources.localeFilters.addAll(listOf("en", "es", "fr", "ja", "zh"))
    }

    // Release signing comes from keystore.properties (local, never committed) or, on CI, from
    // environment variables. Without either, release builds are left unsigned and Gradle says so.
    val keystoreProperties = Properties().apply {
        val file = rootProject.file("keystore.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }
    fun signingValue(property: String, environment: String): String? =
        keystoreProperties.getProperty(property) ?: System.getenv(environment)

    val releaseStoreFile = signingValue("storeFile", "BMUSIC_KEYSTORE_FILE")
    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = rootProject.file(releaseStoreFile)
                storePassword = signingValue("storePassword", "BMUSIC_KEYSTORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "BMUSIC_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "BMUSIC_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            // R8: removes unused code and resources and optimises the rest (smaller, faster app).
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
        // Made by the Baseline Profile plugin from `release`, to generate profiles and run
        // benchmarks. They are only installed on your own test device, so without a release
        // key they fall back to the debug key instead of producing an uninstallable APK.
        val profilingSigning = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        create("benchmarkRelease") {
            signingConfig = profilingSigning
            matchingFallbacks += listOf("release")
        }
        create("nonMinifiedRelease") {
            signingConfig = profilingSigning
            matchingFallbacks += listOf("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
    lint {
        // Accepted, older findings live in lint-baseline.xml. Create it once with
        //   ./gradlew :app:lintDebug -PcreateLintBaseline
        // and commit it; from then on any new finding fails the build. Until the file exists,
        // lint only reports, so release builds are never blocked by a missing baseline.
        val baselineFile = file("lint-baseline.xml")
        if (baselineFile.exists() || providers.gradleProperty("createLintBaseline").isPresent) {
            baseline = baselineFile
        }
        abortOnError = baselineFile.exists()
        checkReleaseBuilds = true
    }
    testOptions {
        // Device-side UI tests (androidTest) run with system animations off, so they are steady.
        animationsDisabled = true
        // JVM unit tests touch Android framework classes (Bundle, Uri, Handler) through the
        // stub android.jar; return defaults instead of throwing "Method ... not mocked".
        unitTests.isReturnDefaultValues = true
    }
}

